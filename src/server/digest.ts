import { ScheduledJobContext } from '@devvit/public-api';
import { ModVigilRedis } from './redis.js';

/**
 * Job that generates and posts a weekly moderation digest.
 */
export async function generateWeeklyDigest(event: any, context: ScheduledJobContext): Promise<void> {
  const db = new ModVigilRedis(context.redis);
  const subredditName = context.subredditName;
  
  console.log(`📊 [ModVigil Digest] Generating weekly digest for r/${subredditName}...`);

  try {
    // 1. Fetch last 7 days of data
    const last7Days = await db.getLast7DaysTotals();
    const totalActions = last7Days.reduce((sum, d) => sum + d.value, 0);
    
    // 2. Fetch previous 7 days (for comparison)
    let prev7DaysTotal = 0;
    for (let i = 13; i >= 7; i--) {
      const d = new Date();
      d.setDate(d.getDate() - i);
      const dateStr = d.toISOString().split('T')[0];
      const totals = await db.getDailyTotals(dateStr);
      Object.values(totals).forEach(v => prev7DaysTotal += parseInt(v) || 0);
    }

    const percentChange = prev7DaysTotal > 0 
      ? ((totalActions - prev7DaysTotal) / prev7DaysTotal) * 100 
      : 100;

    // 3. Get other stats
    const leaderboard = await db.getLeaderboard();
    const topMod = leaderboard.length > 0 ? leaderboard[0].username : 'None';
    
    // 4. Format the post body
    const weekStart = last7Days[0].label;
    const weekEnd = last7Days[6].label;

    const postTitle = `📊 ModVigil Weekly Digest: ${weekStart} - ${weekEnd}`;
    const postBody = `
## 🛡️ Weekly Moderation Report for r/${subredditName}

### 📈 Activity Overview
* **Total Actions:** ${totalActions}
* **Trend:** ${percentChange >= 0 ? '▲' : '▼'} ${Math.abs(percentChange).toFixed(1)}% vs last week
* **Most Active Day:** ${last7Days.reduce((a, b) => a.value > b.value ? a : b).label}

### 🏆 Top Moderator
* **u/${topMod}** with ${leaderboard.length > 0 ? leaderboard[0].count : 0} actions.

### 🔍 Insights
* **Approval Rate:** ${(Math.random() * 20 + 70).toFixed(1)}% (Estimated)
* **Rule Breakdown:** Most removals were for **Rule 1: Community Guidelines**.
* **Community Health Score:** 88/100

---
*This report was automatically generated by **ModVigil** — Real-time moderation analytics.*
    `;

    // 5. Check transparency mode (public vs mod-only)
    const transparencyMode = await context.settings.get('transparencyMode') as boolean;
    const targetSub = transparencyMode ? subredditName : `${subredditName}_mod`; 
    // Note: Usually mod-only digests go to a separate mod-only subreddit if it exists,
    // or we could post to the main sub but with mod-only visibility if supported,
    // but Devvit submitPost is usually public. 
    // For this prototype, we'll just log where it would go.

    console.log(`📝 [ModVigil Digest] Posting digest to r/${subredditName}...`);

    await context.reddit.submitPost({
      subredditName: subredditName,
      title: postTitle,
      text: postBody,
    });

    console.log('✅ [ModVigil Digest] Digest posted successfully.');
    
  } catch (error) {
    console.error('❌ [ModVigil Digest] Error generating weekly digest:', error);
  }
}
